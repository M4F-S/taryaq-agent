#!/usr/bin/env python3
"""tests/test_audit_tamper.py - Cryptographic HMAC Audit Tamper Detection Tests
Dubai Create AI Agents Championship 2026-2027 | Best Societal AI Agent

Asserts that:
1. Untampered 2-record ledger passes verification (exit 0).
2. Mutating patient_egfr in record 2 (e.g. 22.0 -> 90.0) without changing mac exits 1.
3. Mutating canonical payload exits 1.
4. Recomputing mac correctly but corrupting prev_sha256 exits 1 (chain break).
5. Deleting record 1 exits 1 (first record prev_sha256 is not 64 zeros).
6. Missing or short key (< 32 bytes) fails closed (exit 1).
"""

import sys
import os
import json
import hmac
import hashlib
import tempfile
import subprocess
import unittest

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGENT_BIN = os.path.join(ROOT_DIR, "build", "taryaq_agent")
VERIFY_SCRIPT = os.path.join(ROOT_DIR, "tools", "verify_audit.py")
TEST_KEY = "test-key-32-bytes-minimum-000000"


class TestAuditTamper(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not os.path.isfile(AGENT_BIN):
            subprocess.run(["make", "build/taryaq_agent"], cwd=ROOT_DIR, check=True)
        if not os.path.isfile(AGENT_BIN):
            raise FileNotFoundError(f"Binary {AGENT_BIN} not found and build failed.")
        if not os.path.isfile(VERIFY_SCRIPT):
            raise FileNotFoundError(f"Verifier {VERIFY_SCRIPT} not found.")

    def _generate_valid_ledger(self, audit_path: str) -> None:
        """Runs acceptance test to generate a valid 2-record ledger."""
        env = dict(os.environ, TARYAQ_AUDIT_KEY=TEST_KEY)
        cmd = [AGENT_BIN, "--test", "--audit-file", audit_path]
        res = subprocess.run(cmd, env=env, capture_output=True, text=True)
        self.assertEqual(res.returncode, 0, f"Failed to generate ledger: {res.stderr}")
        self.assertTrue(os.path.isfile(audit_path))

    def _run_verifier(self, audit_path: str, key: str = TEST_KEY) -> subprocess.CompletedProcess:
        env = dict(os.environ)
        if key is not None:
            env["TARYAQ_AUDIT_KEY"] = key
        elif "TARYAQ_AUDIT_KEY" in env:
            del env["TARYAQ_AUDIT_KEY"]

        cmd = [sys.executable, VERIFY_SCRIPT, "--ledger", audit_path]
        return subprocess.run(cmd, env=env, capture_output=True, text=True)

    def test_01_valid_ledger_passes_verification(self):
        """Clean 2-record ledger generated by C daemon exits 0 with 'OK 2 records verified'."""
        with tempfile.NamedTemporaryFile(suffix=".jsonl", delete=False) as f:
            ledger_path = f.name
        try:
            self._generate_valid_ledger(ledger_path)
            res = self._run_verifier(ledger_path, key=TEST_KEY)
            self.assertEqual(res.returncode, 0, f"Verifier failed on clean ledger: {res.stderr}")
            self.assertIn("OK 2 records verified", res.stdout)
        finally:
            if os.path.exists(ledger_path):
                os.remove(ledger_path)

    def test_02_tamper_egfr_in_record_2_fails_closed(self):
        """Mutate patient_egfr from 22.0 to 90.0 in record 2 without changing mac -> exits 1."""
        with tempfile.NamedTemporaryFile(suffix=".jsonl", delete=False) as f:
            ledger_path = f.name
        try:
            self._generate_valid_ledger(ledger_path)

            with open(ledger_path, "r", encoding="utf-8") as f:
                lines = [json.loads(line) for line in f if line.strip()]

            self.assertEqual(len(lines), 2)
            # Tamper record 2 eGFR (measured repro from PLAN.md: 22 -> 90)
            lines[1]["patient_egfr"] = 90.0

            with open(ledger_path, "w", encoding="utf-8") as f:
                for rec in lines:
                    f.write(json.dumps(rec) + "\n")

            res = self._run_verifier(ledger_path, key=TEST_KEY)
            self.assertEqual(res.returncode, 1, "Verifier allowed tampered eGFR!")
            self.assertIn("tampering", res.stderr.lower())
        finally:
            if os.path.exists(ledger_path):
                os.remove(ledger_path)

    def test_03_corrupt_prev_sha256_breaks_chain(self):
        """Recompute mac correctly for record 2 but corrupt prev_sha256 -> exits 1 (chain break)."""
        with tempfile.NamedTemporaryFile(suffix=".jsonl", delete=False) as f:
            ledger_path = f.name
        try:
            self._generate_valid_ledger(ledger_path)

            with open(ledger_path, "r", encoding="utf-8") as f:
                lines = [json.loads(line) for line in f if line.strip()]

            self.assertEqual(len(lines), 2)
            # Corrupt prev_sha256 in record 2 to an arbitrary 64-hex string
            corrupt_prev = "a" * 64
            lines[1]["prev_sha256"] = corrupt_prev

            # Even if attacker recomputes the HMAC for record 2 with the corrupted prev:
            msg = f"{corrupt_prev}\n{lines[1]['canonical']}".encode("utf-8")
            lines[1]["mac"] = hmac.new(TEST_KEY.encode("utf-8"), msg, hashlib.sha256).hexdigest()

            with open(ledger_path, "w", encoding="utf-8") as f:
                for rec in lines:
                    f.write(json.dumps(rec) + "\n")

            res = self._run_verifier(ledger_path, key=TEST_KEY)
            self.assertEqual(res.returncode, 1, "Verifier allowed chain break!")
            self.assertIn("chain break", res.stderr.lower())
        finally:
            if os.path.exists(ledger_path):
                os.remove(ledger_path)

    def test_04_delete_record_1_fails_closed(self):
        """Delete record 1 -> record 2's prev_sha256 is not 64 zeros -> exits 1."""
        with tempfile.NamedTemporaryFile(suffix=".jsonl", delete=False) as f:
            ledger_path = f.name
        try:
            self._generate_valid_ledger(ledger_path)

            with open(ledger_path, "r", encoding="utf-8") as f:
                lines = [json.loads(line) for line in f if line.strip()]

            self.assertEqual(len(lines), 2)
            # Delete record 1, keeping only record 2
            with open(ledger_path, "w", encoding="utf-8") as f:
                f.write(json.dumps(lines[1]) + "\n")

            res = self._run_verifier(ledger_path, key=TEST_KEY)
            self.assertEqual(res.returncode, 1, "Verifier accepted orphaned record without root genesis hash!")
            self.assertIn("chain break", res.stderr.lower())
        finally:
            if os.path.exists(ledger_path):
                os.remove(ledger_path)

    def test_05_tamper_canonical_payload_fails_closed(self):
        """Mutate canonical payload directly -> MAC mismatch -> exits 1."""
        with tempfile.NamedTemporaryFile(suffix=".jsonl", delete=False) as f:
            ledger_path = f.name
        try:
            self._generate_valid_ledger(ledger_path)

            with open(ledger_path, "r", encoding="utf-8") as f:
                lines = [json.loads(line) for line in f if line.strip()]

            # Alter canonical drug in record 2
            lines[1]["canonical"] = lines[1]["canonical"].replace("Colchicine", "Aspirin")

            with open(ledger_path, "w", encoding="utf-8") as f:
                for rec in lines:
                    f.write(json.dumps(rec) + "\n")

            res = self._run_verifier(ledger_path, key=TEST_KEY)
            self.assertEqual(res.returncode, 1, "Verifier accepted altered canonical without matching MAC!")
            self.assertIn("mismatch", res.stderr.lower())
        finally:
            if os.path.exists(ledger_path):
                os.remove(ledger_path)

    def test_06_missing_or_short_key_fails_closed(self):
        """Key unset or < 32 bytes fails closed with exit 1."""
        with tempfile.NamedTemporaryFile(suffix=".jsonl", delete=False) as f:
            ledger_path = f.name
        try:
            self._generate_valid_ledger(ledger_path)

            # Unset key
            res_unset = self._run_verifier(ledger_path, key=None)
            self.assertEqual(res_unset.returncode, 1)
            self.assertIn("Audit key missing", res_unset.stderr)

            # Short key (under 32 bytes)
            res_short = self._run_verifier(ledger_path, key="short-key-16-byte")
            self.assertEqual(res_short.returncode, 1)
            self.assertIn("Audit key missing or < 32 bytes", res_short.stderr)
        finally:
            if os.path.exists(ledger_path):
                os.remove(ledger_path)


if __name__ == "__main__":
    unittest.main()
